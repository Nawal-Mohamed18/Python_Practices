# To display texts using print statement
# A SINGLE QUOTE
print('The capybara is the largest rodent in the world.')
# A DOUBLE QUOTE
print("The capybara likes to live in groups.")
# THE BACKSLASH CHARACTER CAN BE USED TO ESCAPE CHARACTERS IN PYTHON
print("The capybara lives in\nsouth America")
# TRIPLE QUOTES CAN BE USED TO DISPLAY MULTIPLE LINES OF TEXT IN PYTHON
print("""This is the strangest way to display text in python I've 
      ever seen. It is called triple quotes and it can be used to display
      multiple lines of text in python. It is also used to write docstrings""")

#WE CAN USE THE + OPERATOR TO CONCATENATE STRINGS IN PYTHON
print("Here is a string." + "HERE IS MORE")
# QUOTES CAN BE BOTH INSIDE ONE ANOTHER IN A ONE PRINT STATEMENT
print('Here is a double quote "' + "HERE IS A SINGLE QUOTE '")

# new method to concat strings in python
print("this is the firt part \" And here is the second part.")
# this also works
print("this is the first part " "And here is the second part.")

# it will print the special characters
print("can I just print a \ in the screen?")

# same as before but using the escape character
print("can I just print a \\ in the screen?")

